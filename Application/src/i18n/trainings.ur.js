/** Return a shallow-localized training tree for UI (English fallback when Urdu missing). */
export function localizeTraining(training, isUr) {
  if (!training || !isUr) return training
  const ur = TRAININGS_UR[training.id]
  if (!ur) return training

  return {
    ...training,
    title: ur.title ?? training.title,
    org: ur.org ?? training.org,
    grade: ur.grade ?? training.grade,
    modules: training.modules.map((mod) => {
      const modUr = ur.modules?.[mod.id]
      return {
        ...mod,
        title: modUr?.title ?? mod.title,
        lessons: mod.lessons.map((lesson) => {
          const lessonUr = modUr?.lessons?.[lesson.id]
          if (!lessonUr) return lesson
          return {
            ...lesson,
            title: lessonUr.title ?? lesson.title,
            topic: lessonUr.topic ?? lesson.topic,
            description: lessonUr.description ?? lesson.description,
            learnings: lessonUr.learnings ?? lesson.learnings,
          }
        }),
      }
    }),
  }
}
