export function localizeEmail(email, isUr) {
  if (!email || !isUr) return email
  const ur = PHISHING_EMAILS_UR[email.id]
  if (!ur) return email
  return {
    ...email,
    subject: ur.subject ?? email.subject,
    body: ur.body ?? email.body,
    date: ur.date ?? email.date,
    indicators: ur.indicators ?? email.indicators,
  }
}
